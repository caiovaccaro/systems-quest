interface Spec {
  id: string;
  name: string;
  blurb: string;
  category: ComponentDef["category"];
  role: ComponentDef["role"];
  machine: ComponentDef["machine"];
  minLevel: number;
  cost: number;
  color: number;
  maxRps: number;
  tier?: number;
  fit?: string;
  accepts?: LinkKind[];
  forgets?: boolean;
  requiresStore?: boolean;
  aggregates?: boolean;
  broadcast?: boolean;
  queueSize?: number;
  baseLatencyMs?: number;
  maxConnections?: number;
  config?: ConfigField[];
}

function piece(spec: Spec): ComponentDef & { minLevel: number } {
  return {
    id: spec.id,
    name: spec.name,
    blurb: spec.blurb,
    category: spec.category,
    role: spec.role,
    shape: spec.role === "store" ? "cyl" : "box",
    placeable: true,
    requiresStore: spec.requiresStore ?? false,
    aggregates: spec.aggregates,
    broadcast: spec.broadcast,
    tier: spec.tier ?? (spec.role === "store" ? 3 : spec.machine === "forward" || spec.machine === "queue" || spec.machine === "gate" ? 1 : 2),
    machine: spec.machine,
    cost: spec.cost,
    color: spec.color,
    maxRps: spec.maxRps,
    baseLatencyMs: spec.baseLatencyMs ?? 8,
    queueSize: spec.queueSize ?? (spec.machine === "queue" ? 5000 : 200),
    maxConnections: spec.maxConnections,
    fit: spec.fit,
    accepts: spec.accepts,
    forgets: spec.forgets,
    config: spec.config ?? [],
    minLevel: spec.minLevel,
  };
}

