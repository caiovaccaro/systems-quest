import type { IslandShape, LevelDef, LinkKind, SceneDef } from "../engine/types";
import { anchor } from "./island";

function crowd(shape: IslandShape): LevelDef["preplaced"] {
  const spot = anchor(shape);
  return [{ defId: "users", x: spot.x, z: spot.z, locked: true }];
}

const blank: [string, string, string] = ["", "", ""];

function scene(place: string, shape: IslandShape, water: number, cliff: number, tileA: number, tileB: number, accent: number): SceneDef {
  return { place, shape, water, cliff, tileA, tileB, accent };
}

function lesson(opts: {
  num: number;
  title: string;
  tease: string;
  product: string;
  brief: string;
  teach: string[];
  glossary: { term: string; means: string }[];
  readWrite: string;
  latency: number;
  nonGoals: string;
  palette: string[];
  cables: LinkKind[];
  scene: SceneDef;
  pass: [string, string, string];
}): LevelDef {
  return {
    id: `l${opts.num}`,
    num: opts.num,
    title: opts.title,
    rank: "Chief Architect",
    playable: true,
    tease: opts.tease,
    product: opts.product,
    brief: opts.brief,
    teach: opts.teach,
    glossary: opts.glossary,
    dau: "One product",
    qps: 16,
    readWrite: opts.readWrite,
    latencySloMs: opts.latency,
    availabilitySlo: 0.95,
    budget: 80,
    region: "One region",
    nonGoals: opts.nonGoals,
    duration: 18,
    seed: opts.num * 17,
    chaos: [{ at: 6, duration: 5, mult: 1.3, label: "Traffic spike" }],
    palette: opts.palette,
    cables: opts.cables,
    scene: opts.scene,
    preplaced: crowd(opts.scene.shape),
    copy: {
      pass: opts.pass,
      warStory: "",
      failUnwired: blank,
      failProtocol: blank,
      failNostore: blank,
      failNoindex: blank,
      failNplusone: blank,
      failPool: blank,
      failSaturated: blank,
      failSlo: blank,
    },
  };
}

